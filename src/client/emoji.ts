/** Matches one `:shortcode:` token; the name excludes whitespace and colons. */
const SHORTCODE = /:([a-z0-9_+-]+):/g

/**
 * Replace every known `:shortcode:` in a string.
 * @param text - source text.
 * @returns the text with known shortcodes substituted; unknown ones are left alone.
 */
export function replaceShortcodes(text: string): string {
  if (!text.includes(':')) return text
  return text.replace(SHORTCODE, (match, name: string) => EMOJI[name] ?? match)
}
